using System.Diagnostics;
using FbStudio.Core.Metadata;
using FirebirdSql.Data.FirebirdClient;

namespace FbStudio.Firebird.Tests;

/// <summary>Backup, restore, validación, sweep y base vacía contra Firebird 3 en Docker (como SYSDBA, que puede crear bases).</summary>
[Collection(nameof(FirebirdCollection))]
public class DatabaseServicesTests(FirebirdFixture fb)
{
    private Core.Profiles.ConnectionProfile Sysdba => fb.Profile with { User = "SYSDBA" };

    [Fact]
    public async Task Backup_y_restore_a_un_archivo_nuevo_y_nunca_sobre_la_base_en_uso()
    {
        var info = await DatabaseServices.FileInfoAsync(Sysdba, fb.Password);
        Assert.Equal("/firebird/data/test", info.Path);                          // el perfil usa el alias «test»
        Assert.Equal("UTF8", info.Charset);
        Assert.Equal(3, info.Dialect);

        var since = await DatabaseServices.ServerTimeAsync(Sysdba, fb.Password);
        var lines = new List<string>();
        await DatabaseServices.BackupAsync(Sysdba, fb.Password, "/firebird/data/servicios.fbk", new BackupOptions(), lines.Add);
        Assert.NotEmpty(lines);
        await WaitAsync(async () => !await DatabaseServices.BackupRunningAsync(Sysdba, fb.Password, since), "el backup no terminó");

        const string Restored = "/firebird/data/servicios_rest.fdb";
        var before = await DatabaseServices.RestoreStateAsync(Sysdba, fb.Password, Restored);
        Assert.True(before.Status == RestoreStatus.Missing, $"{before.Status}: {before.Detail}");
        await DatabaseServices.RestoreAsync(Sysdba, fb.Password, "/firebird/data/servicios.fbk", Restored, new RestoreOptions(), lines.Add);
        await WaitAsync(async () => (await DatabaseServices.RestoreStateAsync(Sysdba, fb.Password, Restored)).Status == RestoreStatus.Online, "el restore no terminó");
        Assert.Equal(FirebirdFixture.Rows, await ScalarAsync(Restored, "SELECT COUNT(*) FROM TURNOS"));

        // Sin «reemplazar», un archivo que ya existe no se pisa; y la base del perfil nunca, ni pidiendo reemplazar.
        await Assert.ThrowsAsync<InvalidOperationException>(() =>
            DatabaseServices.RestoreAsync(Sysdba, fb.Password, "/firebird/data/servicios.fbk", Restored, new RestoreOptions()));
        await Assert.ThrowsAsync<InvalidOperationException>(() =>
            DatabaseServices.RestoreAsync(Sysdba, fb.Password, "/firebird/data/servicios.fbk", fb.Profile.Database, new RestoreOptions(Replace: true)));
        await Assert.ThrowsAsync<InvalidOperationException>(() =>
            DatabaseServices.RestoreAsync(Sysdba, fb.Password, "/firebird/data/servicios.fbk", info.Path, new RestoreOptions(Replace: true)));
        await Assert.ThrowsAsync<InvalidOperationException>(() =>
            DatabaseServices.RestoreAsync(Sysdba with { ReadOnly = true }, fb.Password, "/firebird/data/servicios.fbk", "/firebird/data/otra.fdb", new RestoreOptions()));

        // Solo metadata: la estructura sin filas.
        await DatabaseServices.BackupAsync(Sysdba, fb.Password, "/firebird/data/servicios_meta.fbk", new BackupOptions(MetadataOnly: true), lines.Add);
        await WaitAsync(async () => !await DatabaseServices.BackupRunningAsync(Sysdba, fb.Password, since), "el backup de metadata no terminó");
        await DatabaseServices.RestoreAsync(Sysdba, fb.Password, "/firebird/data/servicios_meta.fbk", "/firebird/data/servicios_meta.fdb", new RestoreOptions(), lines.Add);
        await WaitAsync(async () => (await DatabaseServices.RestoreStateAsync(Sysdba, fb.Password, "/firebird/data/servicios_meta.fdb")).Status == RestoreStatus.Online,
            "el restore de metadata no terminó");
        Assert.Equal(0, await ScalarAsync("/firebird/data/servicios_meta.fdb", "SELECT COUNT(*) FROM TURNOS"));

        await DropAsync(Restored);
        await DropAsync("/firebird/data/servicios_meta.fdb");
    }

    [Fact]
    public async Task Validacion_en_linea_y_sweep_con_la_base_en_uso()
    {
        await using var other = FbConnectionFactory.Create(fb.Profile, fb.Password, "otra");
        await other.OpenAsync();

        var result = await DatabaseServices.ValidateAsync(Sysdba, fb.Password);
        Assert.NotEmpty(result.Lines);
        Assert.True(result.Errors == 0, string.Join("\n", result.Lines));

        await DatabaseServices.SweepAsync(Sysdba, fb.Password);
        await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseServices.SweepAsync(Sysdba with { ReadOnly = true }, fb.Password));
    }

    [Fact]
    public async Task La_base_vacia_tiene_toda_la_estructura_los_datos_elegidos_y_los_generadores_al_dia()
    {
        foreach (var sql in new[]
        {
            "CREATE TABLE COPIA_PADRE (ID INTEGER NOT NULL PRIMARY KEY, NOMBRE VARCHAR(20))",
            "CREATE TABLE COPIA_HIJA (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, PADRE INTEGER REFERENCES COPIA_PADRE (ID), NOTA VARCHAR(20), DOBLE COMPUTED BY (ID * 2))",
            "INSERT INTO COPIA_PADRE VALUES (1, 'uno')",
            "INSERT INTO COPIA_PADRE VALUES (2, 'dos')",
            "INSERT INTO COPIA_PADRE VALUES (3, 'tres')",
            "INSERT INTO COPIA_HIJA (PADRE, NOTA) VALUES (1, 'a')",
            "INSERT INTO COPIA_HIJA (PADRE, NOTA) VALUES (2, 'b')",
            // Un CHECK agregado después: Firebird no revisa las filas viejas, que no lo cumplen.
            "ALTER TABLE COPIA_HIJA ADD CONSTRAINT CHK_NOTA_LARGA CHECK (CHAR_LENGTH(NOTA) > 3)",
            "CREATE TRIGGER COPIA_HIJA_BI FOR COPIA_HIJA BEFORE INSERT AS BEGIN NEW.NOTA = 'TRIGGER ' || NEW.NOTA; END",
            "CREATE SEQUENCE G_COPIA",
            "ALTER SEQUENCE G_COPIA RESTART WITH 77",
        })
            await ExecAsync(fb.Profile.Database, sql);
        const string Empty = "/firebird/data/vacia.fdb";
        try
        {
            var lines = new List<string>();
            var result = await DatabaseServices.CreateEmptyCopyAsync(Sysdba, fb.Password, Empty, new EmptyCopyOptions(Tables: ["COPIA_HIJA"]), lines.Add);
            Assert.True(result.Errors.Count == 0, string.Join("\n\n", result.Errors.Select(e => $"{e.Message}\n--- en ---\n{e.Statement}")));
            Assert.Equal([new TableCopyResult("COPIA_HIJA", 2), new TableCopyResult("COPIA_PADRE", 3)], result.Tables);
            Assert.Contains(lines, l => l.Contains("COPIA_PADRE") && l.Contains("FK"));   // se agregó sola

            // Los datos tal cual (sin pasar por el trigger), el resto vacío y los generadores e identity donde estaban.
            Assert.Equal("a|b", await ScalarAsync(Empty, "SELECT LIST(NOTA, '|') FROM (SELECT NOTA FROM COPIA_HIJA ORDER BY ID)"));
            Assert.Equal(0, await ScalarAsync(Empty, "SELECT COUNT(*) FROM TURNOS"));
            Assert.Equal(77, await ScalarAsync(Empty, "SELECT GEN_ID(G_COPIA, 0) FROM RDB$DATABASE"));
            await using (var c = new FbConnection(FbConnectionFactory.ConnectionString(Sysdba with { Database = Empty }, fb.Password)))
            {
                await c.OpenAsync();
                await using var tx = await c.BeginTransactionAsync();
                await using (var r = await new FbCommand("INSERT INTO COPIA_HIJA (PADRE, NOTA) VALUES (3, 'nueva') RETURNING ID, NOTA", c, tx).ExecuteReaderAsync())
                {
                    Assert.True(await r.ReadAsync());
                    Assert.Equal(3, Convert.ToInt32(r.GetValue(0)));                 // la identity sigue desde 2
                    Assert.Equal("TRIGGER nueva", r.GetString(1));                    // y el trigger ya está
                }
                await Assert.ThrowsAsync<FbException>(() => new FbCommand("INSERT INTO COPIA_HIJA (PADRE, NOTA) VALUES (99, 'huérfana')", c, tx).ExecuteNonQueryAsync());
                await tx.RollbackAsync();
            }

            // Cada objeto con el mismo DDL que en el origen.
            await using var source = new MetadataExplorer(fb.Profile, fb.Password);
            await using var target = new MetadataExplorer(Sysdba with { Database = Empty }, fb.Password);
            foreach (var kind in new[] { DbObjectKind.Table, DbObjectKind.View, DbObjectKind.Procedure, DbObjectKind.Trigger, DbObjectKind.Generator, DbObjectKind.Domain })
                foreach (var obj in await source.LoadObjectsAsync(kind))
                    Assert.Equal((await source.ScriptAsync(obj)).Ddl, (await target.ScriptAsync(obj)).Ddl);

            // Nunca pisa un archivo que ya existe, ni arma sobre la base del perfil.
            await Assert.ThrowsAsync<FbException>(() => DatabaseServices.CreateEmptyCopyAsync(Sysdba, fb.Password, Empty, new EmptyCopyOptions()));
            await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseServices.CreateEmptyCopyAsync(Sysdba, fb.Password, fb.Profile.Database, new EmptyCopyOptions()));
            await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseServices.CreateEmptyCopyAsync(Sysdba, fb.Password, "/firebird/data/test", new EmptyCopyOptions()));
        }
        finally
        {
            await DropAsync(Empty);
            foreach (var sql in new[] { "DROP TRIGGER COPIA_HIJA_BI", "DROP TABLE COPIA_HIJA", "DROP TABLE COPIA_PADRE", "DROP SEQUENCE G_COPIA" })
                await ExecAsync(fb.Profile.Database, sql);
        }
    }

    private static async Task WaitAsync(Func<Task<bool>> done, string message)
    {
        var clock = Stopwatch.StartNew();
        while (!await done())
        {
            Assert.True(clock.Elapsed < TimeSpan.FromMinutes(2), message);
            await Task.Delay(300);
        }
    }

    private async Task<object?> ScalarAsync(string database, string sql)
    {
        await using var c = new FbConnection(FbConnectionFactory.ConnectionString(Sysdba with { Database = database }, fb.Password));
        await c.OpenAsync();
        await using var tx = await c.BeginTransactionAsync();
        var value = await new FbCommand(sql, c, tx).ExecuteScalarAsync();
        return value is long or int or short ? Convert.ToInt32(value) : value;
    }

    private async Task ExecAsync(string database, string sql)
    {
        await using var c = new FbConnection(FbConnectionFactory.ConnectionString(fb.Profile with { Database = database }, fb.Password));
        await c.OpenAsync();
        await using var tx = await c.BeginTransactionAsync();
        await new FbCommand(sql, c, tx).ExecuteNonQueryAsync();
        await tx.CommitAsync();
    }

    private async Task DropAsync(string database)
    {
        try { await FbConnection.DropDatabaseAsync(FbConnectionFactory.ConnectionString(Sysdba with { Database = database }, fb.Password)); }
        catch (FbException) { }
    }
}
